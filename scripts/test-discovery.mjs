import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import ts from 'typescript';
const source = await readFile(new URL('../src/lib/discovery.ts', import.meta.url),'utf8');
const mod={exports:{}};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{module:mod,exports:mod.exports,Set});
const { restoreDiscovery, watchedSeconds }=mod.exports;
const now=1_800_000_000_000;
const restored=restoreDiscovery(['public-a','public-b','new'],{ids:['private-or-hidden','public-b','public-b','public-a'],active:'public-b',time:6.5,at:now-1000},now);
assert.deepEqual(Array.from(restored.ids),['public-b','public-a','new'],'Volver no recupera programas retirados, privados, ocultos o duplicados');
assert.equal(restored.index,0); assert.equal(restored.time,6.5);
assert.equal(restoreDiscovery(['public-a'],{ids:['public-a'],active:'deleted',time:10,at:now},now).time,0,'Una posición ajena al catálogo no se reutiliza');
for(const snapshot of [null,[],{ids:['public-b'],at:now-7_200_001},{ids:['public-b'],at:now+1},{ids:'bad',at:now}]) assert.equal(restoreDiscovery(['public-a'],snapshot,now).time,0);
for(const time of [NaN,Infinity,-10]) assert.equal(restoreDiscovery(['public-a'],{ids:['public-a'],active:'public-a',time,at:now},now).time,0);
assert.equal(watchedSeconds(1,1.25,true),.25);
for(const [a,b,eligible] of [[1,10,true],[13.9,0,true],[1,1.25,false],[0,NaN,true],[Infinity,2,true]]) assert.equal(watchedSeconds(a,b,eligible),0,'Saltos, bucles y reproducción no cualificada no suman interés');
assert.equal(Array.from({length:32},(_,i)=>watchedSeconds(i*.25,(i+1)*.25,true)).reduce((a,b)=>a+b,0),8);
console.log('Descubrir: restauración segura, catálogo actualizado y tiempo real sin saltos aprobados.');
